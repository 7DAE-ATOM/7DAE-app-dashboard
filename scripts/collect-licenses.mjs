/**
 * Copies the licences of everything the deliverable redistributes into
 * `out/licenses/`.
 *
 * Self-hosting fonts means shipping their binaries, and the SIL Open Font
 * Licence requires its text to travel with them. Copying from `node_modules`
 * at build time rather than committing snapshots keeps the text in step with
 * the version actually installed — a committed copy silently goes stale on the
 * next upgrade, which is the failure mode that makes licence files worthless.
 *
 * Run after `npm run build` and before `npm run check:external-urls`, which
 * skips this directory (OFL texts cite scripts.sil.org).
 */
import { copyFileSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DEST = join(ROOT, "out", "licenses");

const FONTS = [
  ["@fontsource-variable/inter", "OFL-Inter.txt"],
  ["@fontsource-variable/jetbrains-mono", "OFL-JetBrainsMono.txt"],
];

if (!existsSync(join(ROOT, "out"))) {
  console.error("out/ does not exist — run `npm run build` first.");
  process.exit(1);
}
mkdirSync(DEST, { recursive: true });

for (const [pkg, target] of FONTS) {
  const source = join(ROOT, "node_modules", pkg, "LICENSE");
  if (!existsSync(source)) {
    console.error(`Missing licence for ${pkg} at ${source}`);
    process.exit(1);
  }
  copyFileSync(source, join(DEST, target));
  console.log(`  ${pkg} -> licenses/${target}`);
}

/** The map outlines are baked into JavaScript, so nothing in the deliverable
 *  otherwise says where they come from. */
writeFileSync(
  join(DEST, "NaturalEarth.txt"),
  `Map outlines
============

The country outlines in this application are derived from Natural Earth
(https://www.naturalearthdata.com/), made available via the npm package
"world-atlas" (https://github.com/topojson/world-atlas).

Natural Earth raster and vector map data is in the PUBLIC DOMAIN. No permission
is needed to use it, and no attribution is required — the above is stated so
that the provenance of the data remains traceable, since the outlines are
compiled into JavaScript rather than shipped as a data file.

Generated by scripts/generate-world-map.mjs.
`,
  "utf-8",
);
console.log("  Natural Earth -> licenses/NaturalEarth.txt");
